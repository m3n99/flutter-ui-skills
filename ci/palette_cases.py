#!/usr/bin/env python3
"""CI only: writes the curated palettes as Dart, for ci/palettes_test.dart,
with the seeds palette.py would put in AppThemeConfig.

    python3 ci/palette_cases.py > test/ci/curated_palettes.dart
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "plugins/flutter-modern-ui/skills/flutter-modern-ui/scripts"))
import palette  # noqa: E402


def main():
    print("// Generated by ci/palette_cases.py from assets/palettes/curated.json. Don't edit.")
    print("import 'package:flutter/painting.dart';")
    print()
    print("typedef CuratedPalette = ({String name, Color seed, Color? secondary, Color? tertiary, Color? neutral});")
    print()
    print("const List<CuratedPalette> curatedPalettes = [")
    for candidate in palette.load_curated():
        seeds = {field: hex_code for field, hex_code, _ in candidate.seeds()}

        def color(field):
            return f"Color(0xFF{seeds[field]})" if field in seeds else "null"

        name = candidate.name.replace("'", "\\'")
        print(
            f"  (name: '{name}', seed: {color('seed')}, secondary: {color('secondarySeed')}, "
            f"tertiary: {color('tertiarySeed')}, neutral: {color('neutralSeed')}),"
        )
    print("];")


if __name__ == "__main__":
    main()
